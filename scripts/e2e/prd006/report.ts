/**
 * `docs/prds/006-validation-report.md` (task 5.14 step 8): a summary table,
 * then one table per flow with check, status, expected / actual and timings.
 */

import { writeFileSync } from 'node:fs';
import { FLOW_IDS } from './config.ts';
import type { CheckResult, CheckStatus, FlowResult } from './flows/types.ts';

const ICON: Record<CheckStatus, string> = { pass: '✅', fail: '❌', pending: '⏳', skipped: '⏭️' };

export interface ReportMeta {
  readonly startedAt: Date;
  readonly ms: number;
  readonly commit: string;
  readonly args: string;
  readonly setup: readonly string[];
}

export function flowStatus(f: FlowResult): CheckStatus {
  const s = f.checks.map((c) => c.status);
  if (s.includes('fail')) return 'fail';
  if (s.includes('pending')) return 'pending';
  if (s.length > 0 && s.every((x) => x === 'skipped')) return 'skipped';
  return 'pass';
}

const cell = (v: unknown): string => {
  if (v === undefined) return '';
  const s = typeof v === 'string' ? v : JSON.stringify(v);
  const short = s.length > 400 ? `${s.slice(0, 400)}…` : s;
  return short.replace(/\|/g, '\\|').replace(/\n/g, ' ');
};

const secs = (ms: number) => `${(ms / 1000).toFixed(1)} s`;

function checkRow(c: CheckResult): string {
  const status =
    c.status === 'pending'
      ? `${ICON.pending} pending-${c.pendingOn ?? '?'}`
      : `${ICON[c.status]} ${c.status}`;
  return `| ${cell(c.name)} | ${status} | ${cell(c.expected)} | ${cell(c.actual ?? c.detail)} | ${secs(c.ms)} |`;
}

export function renderReport(flows: readonly FlowResult[], meta: ReportMeta): string {
  const ordered = [...flows].sort((a, b) => FLOW_IDS.indexOf(a.id) - FLOW_IDS.indexOf(b.id));
  const all = ordered.flatMap((f) => f.checks);
  const count = (s: CheckStatus) => all.filter((c) => c.status === s).length;
  const lines = [
    '# PRD-006 validation report',
    '',
    `Generated by \`pnpm prd006:validate ${meta.args}\` at ${meta.startedAt.toISOString()} on \`${meta.commit}\`, in ${secs(meta.ms)}.`,
    'Expected values come from `docs/prds/006-validation.md` (F1 literals, F3 goldens) and the',
    'TypeScript oracle (`scripts/e2e/prd006/oracle.ts`, a port of `docs/reference/samples/generate.py`).',
    '',
    `**${count('pass')} passed · ${count('fail')} failed · ${count('pending')} pending · ${count('skipped')} skipped** (checks)`,
    '',
    '| Flow | Title | Data | Result | Checks | Time |',
    '|---|---|---|---|---|---|',
    ...ordered.map((f) => {
      const st = flowStatus(f);
      const pass = f.checks.filter((c) => c.status === 'pass').length;
      return `| ${f.id} | ${f.title} | ${f.data} | ${ICON[st]} ${st} | ${pass}/${f.checks.length} | ${secs(f.ms)} |`;
    }),
    '',
    '## Setup',
    '',
    ...meta.setup.map((s) => `- ${s}`),
    '',
  ];
  for (const f of ordered) {
    lines.push(
      `## ${f.id} — ${f.title} (${f.data})`,
      '',
      '| Check | Status | Expected | Actual / detail | Time |',
      '|---|---|---|---|---|',
    );
    lines.push(...f.checks.map(checkRow), '');
  }
  lines.push(
    'Legend: ✅ pass · ❌ fail · ⏳ pending-<package> (feature not merged yet; not a pass) · ⏭️ skipped (not run in this invocation).',
    '',
  );
  return lines.join('\n');
}

export function writeReport(path: string, flows: readonly FlowResult[], meta: ReportMeta): void {
  writeFileSync(path, renderReport(flows, meta));
}
